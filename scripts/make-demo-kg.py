#!/usr/bin/env python3
"""Generate and SIGN the demo Knowledge Graph the quickstart boots with.

Produces ``reference-implementation/examples/knowledge-graphs/kg.json``
in the runtime flat-rule shape, signed with a locally generated ed25519
demo key, so the quickstart boots CONFORMANTLY (KG_REQUIRE_SIGNATURE=true)
without anyone committing a private key to the repository.

The rules are the SKI Evals energy golden-dataset KG — ten obligations
with jurisdiction and effective-date scoping, every one mechanically
checkable by the Symbolic Verifier.

The demo signing key is written to ``reference-implementation/kg-signing/``
(gitignored), deliberately NOT under ``tls/``: the compose stacks mount
``tls/`` into the runtime container, and the runtime must never hold the
key that signs its Knowledge Graphs. It attests nothing beyond "this
machine generated this demo KG" — production keys belong to your
Knowledge Graph Owner, per docs/governance.md.

Framework v3.2.0: the runtime loads a KG only if its signature verifies
against an operator-pinned trust anchor (``SKI_KG_TRUST_ANCHORS``), never
against the key embedded in the KG. This script therefore also writes
the demo public key as a one-key PEM trust-anchor bundle,
``reference-implementation/kg-signing/kg-trust-anchors.pem``, which the
compose stacks mount read-only and pin. Print its key ID with
``--print-key-id``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
for p in (REPO / "reference-implementation" / "src", REPO / "tools" / "ski-schemas" / "src"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

SOURCE = REPO / "evals" / "datasets" / "energy" / "eval-kg.json"
OUT = REPO / "reference-implementation" / "examples" / "knowledge-graphs" / "kg.json"
KEY_DIR = REPO / "reference-implementation" / "kg-signing"
TRUST_ANCHORS = KEY_DIR / "kg-trust-anchors.pem"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--print-key-id",
        action="store_true",
        help="Print only the demo trust anchor's key ID (sha256:<hex>) after generating.",
    )
    args = parser.parse_args(argv)

    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    metadata = dict(src["metadata"])
    metadata["description"] = (
        "DEMO Knowledge Graph (energy) — generated and signed locally by "
        "scripts/make-demo-kg.py for the quickstart. Not regulatory advice."
    )
    rules, tag_registry = src["rules"], src["tag_registry"]

    canonical = json.dumps(
        {"metadata": metadata, "rules": rules, "tag_registry": tag_registry},
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")

    KEY_DIR.mkdir(parents=True, exist_ok=True)
    key_path = KEY_DIR / "demo-kg-signing.key"
    if key_path.exists():
        key = serialization.load_pem_private_key(key_path.read_bytes(), password=None)
        assert isinstance(key, Ed25519PrivateKey)
    else:
        key = Ed25519PrivateKey.generate()
        key_path.write_bytes(
            key.private_bytes(
                serialization.Encoding.PEM,
                serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption(),
            )
        )
        key_path.chmod(0o600)

    public_pem = key.public_key().public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    )
    (KEY_DIR / "demo-kg-signing.pub").write_bytes(public_pem)
    # The operator trust-anchor bundle the runtime pins (SKI_KG_TRUST_ANCHORS).
    # Public key only; a production bundle may hold several keys (rotation).
    TRUST_ANCHORS.write_bytes(
        b"# SKI KG trust anchors (SKI_KG_TRUST_ANCHORS) - DEMO key generated by\n"
        b"# scripts/make-demo-kg.py. Replace with your KG Owner's public key(s).\n" + public_pem
    )
    TRUST_ANCHORS.chmod(0o644)  # public material; the runtime container (uid 10001) reads it

    kg = {
        "metadata": metadata,
        "rules": rules,
        "tag_registry": tag_registry,
        "signature": {
            "algorithm": "ed25519",
            "public_key_pem": public_pem.decode("ascii"),
            "value_hex": key.sign(canonical).hex(),
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(kg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # Round-trip: refuse to emit a KG the runtime would refuse to load,
    # verifying it exactly as the runtime will: against the pinned anchor.
    from ski_model.kg_loader import KGTrustPolicy, load_signed_kg, load_trust_anchors

    anchors = load_trust_anchors(TRUST_ANCHORS)
    loaded = load_signed_kg(OUT, require_signature=True, trust=KGTrustPolicy(anchors=anchors))
    if not (loaded.signature_verified and loaded.kg_trust == "anchored"):
        raise SystemExit("demo KG did not verify against its own trust-anchor bundle")
    if args.print_key_id:
        print(loaded.signer_key_id)
        return 0
    print(f"Signed demo KG written to {OUT.relative_to(REPO)} ({len(rules)} rules, signature verified).")
    print(
        f"Trust anchor written to {TRUST_ANCHORS.relative_to(REPO)} "
        f"(key ID {loaded.signer_key_id}); pin it with SKI_KG_TRUST_ANCHORS."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
