"""Model weight-hash pinning (``SKI_MODEL_FILE_SHA256``) — fail-closed behaviour.

Covers the pure helpers in :mod:`ski_model.v3.backends.model_hash` and how
the Ollama and vLLM backends apply them at construction (= runtime start).
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import httpx
import pytest
from pytest_httpx import HTTPXMock

from ski_model.v3 import PROMPT_TEMPLATE_HASH, STRUCTURED_GRAMMAR_HASH, OllamaV3Backend, VLLMV3Backend
from ski_model.v3.backends.model_hash import (
    ModelHashError,
    ModelHashMismatchError,
    RemoteModelError,
    expected_model_hash,
    name_commitment,
    normalize_sha256,
    sha256_file,
    weights_digest_from_modelfile,
)

OLLAMA = "http://ollama-pin:11434"
VLLM = "http://vllm-pin:8000"
BLOB = "c" * 64
OTHER = "d" * 64


def _modelfile(blob: str = BLOB) -> str:
    return (
        '# Modelfile generated by "ollama show"\n'
        "# To build a new Modelfile based on this, replace FROM with:\n"
        "# FROM qwen2.5:7b-instruct\n\n"
        f"FROM /root/.ollama/models/blobs/sha256-{blob}\n"
        f"FROM /root/.ollama/models/blobs/sha256-{OTHER}\n"  # projector: never the weights
        'TEMPLATE """{{ .Prompt }}"""\n'
        "PARAMETER stop <|im_end|>\n"
    )


def _ollama(expected: str | None = None) -> OllamaV3Backend:
    return OllamaV3Backend(
        base_url=OLLAMA,
        model_name="qwen2.5:7b-instruct",
        seed=42,
        max_tokens=64,
        prompt_template_hash=PROMPT_TEMPLATE_HASH,
        structured_grammar_hash=STRUCTURED_GRAMMAR_HASH,
        expected_model_hash=expected,
    )


def _vllm(httpx_mock: HTTPXMock, *, sha: str | None = None, path: str | None = None) -> VLLMV3Backend:
    httpx_mock.add_response(url=f"{VLLM}/v1/models", json={"data": [{"id": "m"}]})
    return VLLMV3Backend(
        base_url=VLLM,
        model_name="m",
        seed=42,
        max_tokens=64,
        prompt_template_hash=PROMPT_TEMPLATE_HASH,
        structured_grammar_hash=STRUCTURED_GRAMMAR_HASH,
        model_file_sha256=sha,
        model_file_path=path,
    )


# ---- Helpers ------------------------------------------------------------------


class TestHelpers:
    @pytest.mark.parametrize("raw", [BLOB, BLOB.upper(), f"sha256:{BLOB}", f"sha256-{BLOB}", f"  {BLOB}\n"])
    def test_normalize_accepts_hex_with_optional_prefix(self, raw: str) -> None:
        assert normalize_sha256(raw) == BLOB

    @pytest.mark.parametrize("raw", ["", "abc", "z" * 64, BLOB + "0", f"{BLOB}  model.gguf", "md5:" + BLOB])
    def test_normalize_rejects_anything_else(self, raw: str) -> None:
        with pytest.raises(ModelHashError, match="SHA-256"):
            normalize_sha256(raw)

    def test_expected_model_hash_from_env(self) -> None:
        assert expected_model_hash({}) is None
        assert expected_model_hash({"SKI_MODEL_FILE_SHA256": "   "}) is None
        assert expected_model_hash({"SKI_MODEL_FILE_SHA256": f"sha256:{BLOB}"}) == BLOB
        with pytest.raises(ModelHashError):
            expected_model_hash({"SKI_MODEL_FILE_SHA256": "not-a-digest"})

    def test_sha256_file_streams(self, tmp_path: Path) -> None:
        f = tmp_path / "w.gguf"
        f.write_bytes(b"weights" * 1000)
        assert sha256_file(f) == hashlib.sha256(b"weights" * 1000).hexdigest()

    def test_name_commitment_is_labelled_placeholder(self) -> None:
        expected = "sha256:" + hashlib.sha256(b"ollama:m").hexdigest()
        assert name_commitment("ollama", "m") == expected

    def test_modelfile_first_from_line_is_the_weights_blob(self) -> None:
        assert weights_digest_from_modelfile(_modelfile()) == BLOB

    @pytest.mark.parametrize(
        "modelfile",
        [
            None,
            42,
            "",
            "# FROM /root/.ollama/models/blobs/sha256-" + BLOB,  # comment only
            "FROM qwen2.5:7b-instruct\n",  # MLX / name reference
            "FROM /models/sha256-tooshort\n",
            'TEMPLATE """x"""\n',
        ],
    )
    def test_modelfile_without_blob_yields_none(self, modelfile: object) -> None:
        assert weights_digest_from_modelfile(modelfile) is None

    def test_modelfile_windows_and_colon_blob_names(self) -> None:
        assert weights_digest_from_modelfile(f"FROM C:\\ollama\\blobs\\sha256:{BLOB}") == BLOB


# ---- Ollama -------------------------------------------------------------------


class TestOllamaPin:
    def test_matching_pin_is_verified(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", json={"modelfile": _modelfile()})
        b = _ollama(BLOB)
        assert b.model_weight_hash == f"sha256:{BLOB}"
        assert b.model_hash_verified is True
        assert b.model_hash_source == "verified-backend-digest"

    def test_show_request_names_the_model(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", json={"modelfile": _modelfile()})
        _ollama(BLOB)
        request = httpx_mock.get_requests()[0]
        assert request.read() == b'{"model":"qwen2.5:7b-instruct"}'

    def test_mismatching_pin_refuses_to_start(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", json={"modelfile": _modelfile(BLOB)})
        with pytest.raises(ModelHashMismatchError, match="mismatch"):
            _ollama(OTHER)

    def test_pin_with_unreachable_ollama_refuses(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_exception(httpx.ConnectError("down"), url=f"{OLLAMA}/api/show")
        with pytest.raises(ModelHashError, match="cannot be verified"):
            _ollama(BLOB)

    def test_pin_with_http_error_refuses(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", status_code=404, json={"error": "not found"})
        with pytest.raises(ModelHashError, match="cannot be verified"):
            _ollama(BLOB)

    def test_pin_with_non_json_show_refuses(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", text="<html>proxy</html>")
        with pytest.raises(ModelHashError, match="cannot be verified"):
            _ollama(BLOB)

    def test_pin_without_blob_refuses(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", json={"modelfile": "FROM qwen2.5:7b-instruct\n"})
        with pytest.raises(ModelHashError, match="no content-addressed"):
            _ollama(BLOB)

    @pytest.mark.parametrize("expected", [None, BLOB])
    @pytest.mark.parametrize("field", ["remote_host", "remote_model"])
    def test_remote_model_always_refuses(
        self, httpx_mock: HTTPXMock, field: str, expected: str | None
    ) -> None:
        httpx_mock.add_response(
            url=f"{OLLAMA}/api/show",
            json={"modelfile": _modelfile(), field: "https://ollama.com:443"},
        )
        with pytest.raises(RemoteModelError, match="sovereign boundary"):
            _ollama(expected)

    def test_unreachable_without_pin_records_unverified_name_commitment(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_exception(httpx.ConnectError("down"), url=f"{OLLAMA}/api/show")
        b = _ollama()
        assert b.model_weight_hash == name_commitment("ollama", "qwen2.5:7b-instruct")
        assert b.model_hash_verified is False
        assert b.model_hash_source == "name-commitment"

    def test_non_object_show_body_without_pin_is_unverified(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(url=f"{OLLAMA}/api/show", json=["not", "an", "object"])
        b = _ollama()
        assert b.model_hash_verified is False
        assert b.model_hash_source == "name-commitment"


# ---- vLLM ---------------------------------------------------------------------


class TestVLLMPin:
    def test_file_matching_pin_is_verified(self, httpx_mock: HTTPXMock, tmp_path: Path) -> None:
        weights = tmp_path / "model.gguf"
        weights.write_bytes(b"gguf-bytes")
        digest = hashlib.sha256(b"gguf-bytes").hexdigest()
        b = _vllm(httpx_mock, sha=f"sha256:{digest}", path=str(weights))
        assert b.model_weight_hash == f"sha256:{digest}"
        assert b.model_hash_verified is True
        assert b.model_hash_source == "verified-file-digest"
        assert b.model_id == "m"

    def test_file_mismatching_pin_refuses(self, httpx_mock: HTTPXMock, tmp_path: Path) -> None:
        weights = tmp_path / "model.gguf"
        weights.write_bytes(b"tampered")
        with pytest.raises(ModelHashMismatchError):
            _vllm(httpx_mock, sha=BLOB, path=str(weights))

    def test_unreadable_file_refuses(self, httpx_mock: HTTPXMock, tmp_path: Path) -> None:
        with pytest.raises(ModelHashError, match="cannot be read"):
            _vllm(httpx_mock, sha=BLOB, path=str(tmp_path / "missing.gguf"))

    def test_pin_without_file_is_operator_asserted_not_verified(self, httpx_mock: HTTPXMock) -> None:
        b = _vllm(httpx_mock, sha=BLOB)
        assert b.model_weight_hash == f"sha256:{BLOB}"
        assert b.model_hash_verified is False
        assert b.model_hash_source == "operator-asserted"

    def test_file_without_pin_is_recorded_unverified(self, httpx_mock: HTTPXMock, tmp_path: Path) -> None:
        weights = tmp_path / "model.gguf"
        weights.write_bytes(b"w")
        b = _vllm(httpx_mock, path=str(weights))
        assert b.model_weight_hash == "sha256:" + hashlib.sha256(b"w").hexdigest()
        assert b.model_hash_verified is False
        assert b.model_hash_source == "file-digest"

    def test_neither_is_a_labelled_name_commitment(self, httpx_mock: HTTPXMock) -> None:
        b = _vllm(httpx_mock)
        assert b.model_weight_hash == name_commitment("vllm", "m")
        assert b.model_hash_verified is False
        assert b.model_hash_source == "name-commitment"

    def test_malformed_pin_refuses(self, httpx_mock: HTTPXMock) -> None:
        with pytest.raises(ModelHashError):
            _vllm(httpx_mock, sha="sha256:nothex")
