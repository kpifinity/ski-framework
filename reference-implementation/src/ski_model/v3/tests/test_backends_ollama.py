"""Tests for OllamaV3Backend using ``pytest-httpx`` to mock Ollama.

We don't talk to a live Ollama in CI; pytest-httpx intercepts HTTP
calls and lets us assert on request payloads and inject fake responses.
"""

from __future__ import annotations

import json
from typing import Any, Dict

import pytest
from pytest_httpx import HTTPXMock

from ski_model.v3 import PROMPT_TEMPLATE_HASH, STRUCTURED_GRAMMAR_HASH, OllamaV3Backend
from ski_model.v3.evaluator import PROMPT_TEMPLATE_ID


def _backend(base_url: str = "http://ollama-test:11434") -> OllamaV3Backend:
    return OllamaV3Backend(
        base_url=base_url,
        model_name="test-model:1b",
        seed=42,
        max_tokens=256,
        prompt_template_hash=PROMPT_TEMPLATE_HASH,
        structured_grammar_hash=STRUCTURED_GRAMMAR_HASH,
    )


def _good_response_text() -> str:
    return json.dumps(
        {
            "verdict": "CLEAR",
            "reasoning": "Within limit.",
            "kg_citations": [{"node_id": "ob.x", "version": "v1", "role": "obligation"}],
            "formalizable_assertions": [
                {
                    "predicate": "must_not_exceed",
                    "metric": "so2_ppm",
                    "value": 100,
                    "observed": 50,
                    "satisfied": True,
                    "obligation_id": "ob.x",
                }
            ],
        }
    )


# ---- Provenance / model weight hash -------------------------------------------


class TestProvenance:
    def test_backend_protocol_properties(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/show",
            method="POST",
            json={"details": {"digest": "sha256:zzz"}},
        )
        backend = _backend()
        assert backend.prompt_template_id == PROMPT_TEMPLATE_ID
        assert backend.prompt_template_hash == PROMPT_TEMPLATE_HASH
        assert backend.structured_grammar_hash == STRUCTURED_GRAMMAR_HASH

    def test_untrusted_digest_fields_are_not_weight_hashes(self, httpx_mock: HTTPXMock) -> None:
        """``/api/show`` has no weights ``digest`` field; ``details.parent_model``
        is a model *name*. v3.1.x reported such values as the weight hash.
        They are ignored now: no blob => labelled name commitment, unverified."""
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/show",
            method="POST",
            json={"digest": "sha256:" + "a" * 64, "details": {"parent_model": "qwen2.5:7b"}},
        )
        backend = _backend()
        assert backend.model_weight_hash != "sha256:" + "a" * 64
        assert backend.model_hash_verified is False
        assert backend.model_hash_source == "name-commitment"

    def test_model_weight_hash_is_the_weights_blob_digest(self, httpx_mock: HTTPXMock) -> None:
        blob = "b" * 64
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/show",
            method="POST",
            json={
                "modelfile": (
                    '# Modelfile generated by "ollama show"\n'
                    "# To build a new Modelfile based on this, replace FROM with:\n"
                    "# FROM test-model:1b\n\n"
                    f"FROM /root/.ollama/models/blobs/sha256-{blob}\n"
                    'TEMPLATE """{{ .Prompt }}"""\n'
                ),
            },
        )
        backend = _backend()
        assert backend.model_weight_hash == "sha256:" + blob
        assert backend.model_hash_verified is False  # no pin configured
        assert backend.model_hash_source == "backend-digest"
        assert backend.model_id == "test-model:1b"

    def test_model_weight_hash_falls_back_when_show_404s(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/show",
            method="POST",
            status_code=404,
            json={"error": "model not found"},
        )
        backend = _backend()
        # Vendor commitment fallback — sha256("ollama:test-model:1b")
        assert backend.model_weight_hash.startswith("sha256:")
        assert len(backend.model_weight_hash) == 71

    def test_model_weight_hash_falls_back_when_digest_missing(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/show",
            method="POST",
            json={"details": {}, "modelfile": "FROM ..."},
        )
        backend = _backend()
        assert backend.model_weight_hash.startswith("sha256:")


# ---- Request shape ------------------------------------------------------------


class TestRequestPayload:
    @pytest.mark.asyncio
    async def test_request_is_deterministic_and_json_format(self, httpx_mock: HTTPXMock) -> None:
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/show",
            method="POST",
            json={"details": {"digest": "sha256:zzz"}},
        )
        httpx_mock.add_response(
            url="http://ollama-test:11434/api/generate",
            method="POST",
            json={"response": _good_response_text()},
        )

        backend = _backend()
        await backend.evaluate(
            measurement={"so2_ppm": 50},
            kg_snapshot={"version": "v1", "obligations": []},
            seed=7,
        )

        # Last request is /api/generate; verify its body.
        requests = httpx_mock.get_requests()
        generate_req = next(r for r in requests if r.url.path == "/api/generate")
        body: Dict[str, Any] = json.loads(generate_req.content)
        assert body["model"] == "test-model:1b"
        assert body["stream"] is False
        # Schema-constrained decoding: the full RESPONSE_GRAMMAR rides in the
        # request so Ollama enforces the output contract at generation time.
        from ski_model.v3.evaluator import RESPONSE_GRAMMAR

        assert body["format"] == RESPONSE_GRAMMAR
        opts = body["options"]
        assert opts["temperature"] == 0
        assert opts["seed"] == 7  # The seed kwarg from evaluate(), not the constructor.
        assert opts["num_predict"] == 256
        assert opts["top_p"] == 1.0
        assert opts["top_k"] == 1
        # The prompt must include the canonical PROMPT_TEMPLATE markers.
        assert "MEASUREMENT:" in body["prompt"]
        assert "KG SNAPSHOT:" in body["prompt"]


